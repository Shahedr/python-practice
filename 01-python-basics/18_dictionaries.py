# Dictionaries Practice

product = {
    "name": "Laptop",
    "price": 899.99,
    "in_stock": True
}

print(product)
print(product["name"])
print(product["price"])

product["price"] = 849.99
print(product["price"])

product["category"] = "Electronics"
print(product)

